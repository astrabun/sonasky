/**
 * A glyph as its pixels' columns, left to right (each a bitmask, bit 0 on top),
 * plus how far to move right before the next glyph.
 */
interface Glyph {
  columns: number[];
  advance: number;
}

/** Rows from the top of the tallest glyph to the bottom of the lowest descender. */
export const BITMAP_FONT_HEIGHT: Record<BitmapFont, number> = { pixel: 8, tiny: 6 };

// glcdfont.c is fixed-width, with every glyph in a 5-column box. We drop the
// box's empty columns so text is proportional ("i" is narrower than "m"), then
// leave 1px before the next glyph. A space has no pixels to keep, so it gets 3.
const PIXEL_GLYPHS = new Map<string, Glyph>(
  Array.from({ length: 0x7e - 0x20 + 1 }, (_, i) => {
    const box = GLCD_FONT.slice(i * 5, i * 5 + 5);
    const first = box.findIndex((col) => col !== 0);
    const columns = first === -1 ? [] : box.slice(first, box.findLastIndex((col) => col !== 0) + 1);
    return [String.fromCharCode(0x20 + i), { columns, advance: (columns.length || 3) + 1 }];
  }),
);

// Tom Thumb is already proportional, so we keep its own advance widths.
// Glyph tops are 5 rows above the baseline at most, so row = yOffset + 5.
const TOM_THUMB_ASCENT = 5;
const TINY_GLYPHS = new Map<string, Glyph>(
  TOM_THUMB_GLYPHS.map(([offset, width, height, advance, xOffset, yOffset], i) => {
    const bit = (n: number) => (TOM_THUMB_BITMAPS[(offset * 8 + n) >> 3] >> (7 - (n & 7))) & 1;
    const columns = Array.from({ length: xOffset + width }, () => 0);
    for (let y = 0; y < height; y++) {
      for (let x = 0; x < width; x++) {
        if (bit(y * width + x)) columns[xOffset + x] |= 1 << (TOM_THUMB_ASCENT + yOffset + y);
      }
    }
    return [String.fromCharCode(0x20 + i), { columns, advance }];
  }),
);

/** The glyph for `ch`, or "?" for characters the font doesn't have. */
function glyphFor(ch: string, font: BitmapFont): Glyph {
  const table = font === "pixel" ? PIXEL_GLYPHS : TINY_GLYPHS;
  return table.get(ch) ?? table.get("?")!;
}

