export function measureBitmapText(text: string, font: BitmapFont): number {
  let width = 0;
  for (const ch of text) width += glyphFor(ch, font).advance;
  // Every advance includes the 1px gap before the next glyph; the last one has no next glyph.
  return Math.max(0, width - 1);
}

/** Draw `text` with its top-left corner at (x, y), in the target's current fillStyle. */
export function drawBitmapText(
  target: PixelTarget,
  text: string,
  font: BitmapFont,
  x: number,
  y: number,
): void {
  let cx = x;
  for (const ch of text) {
    const glyph = glyphFor(ch, font);
    glyph.columns.forEach((col, dx) => {
      for (let dy = 0; col >> dy; dy++) {
        if (col & (1 << dy)) target.fillRect(cx + dx, y + dy, 1, 1);
      }
    });
    cx += glyph.advance;
  }
}
